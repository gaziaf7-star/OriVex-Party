import 'package:general/src/core/index.dart';
import 'package:general/src/features/home/domain/entities/create_room_entity.dart';

class CreateRoomModel extends CreateRoomEntity {
  const CreateRoomModel({
    required super.id,
    required super.ownerId,
    required super.ownerUuid,
    required super.ownerName,
    required super.ownerImage,
    required super.roomId,
    required super.ownerSpecialId,
    required super.name,
    required super.mode,
    required super.visitorsCount,
    required super.cover,
    required super.isHot,
    required super.session,
    required super.giftPrice,
    required super.isPopular,
    required super.roomStatus,
    required super.passwordStatus,
    required super.roomIntro,
